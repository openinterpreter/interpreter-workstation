#!/usr/bin/env electron
/**
 * Electron PDF Integration Smoke Test
 *
 * Generates real PDFs using Chromium printToPDF and validates they were created.
 * Usage:
 *   pnpm -C app exec electron scripts/pdf-integration-smoke.mjs
 *   pnpm -C app exec electron scripts/pdf-integration-smoke.mjs --open
 *
 * Flags:
 *   --open   Reveal generated PDFs in Finder after test run (macOS).
 */

import { app, BrowserWindow } from 'electron';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { appendFile, mkdir, rm, stat, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { PDFDocument } from 'pdf-lib';

const execFileAsync = promisify(execFile);
const shouldOpenFinder = process.argv.includes('--open');

const OUTPUT_ROOT = resolve(process.cwd(), 'tmp', 'pdf-integration-output');

