function createPrintWindow() {
  return new BrowserWindow({
    show: false,
    width: 1280,
    height: 1800,
    backgroundColor: '#ffffff',
    webPreferences: {
      sandbox: true,
      contextIsolation: true,
      nodeIntegration: false,
    },
  });
}

async function renderHtmlToPdf(win, htmlPath, pdfPath, printOptions) {
  await win.webContents.loadURL(pathToFileURL(htmlPath).toString());
  await win.webContents.executeJavaScript(
    `(async () => {
      if (document.readyState === 'loading') {
        await new Promise(resolve => document.addEventListener('DOMContentLoaded', resolve, { once: true }));
      }
      if (document.fonts?.ready) {
        try { await document.fonts.ready; } catch {}
      }
      await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
    })();`,
    true
  );

  const pdfBytes = await win.webContents.printToPDF(printOptions);
  await writeFile(pdfPath, pdfBytes);
}

async function validatePdf(pdfPath, expectedPages) {
  const fileStat = await stat(pdfPath);
  if (fileStat.size <= 0) {
    throw new Error(`Generated PDF is empty: ${pdfPath}`);
  }

  const pdfBytes = await import('node:fs/promises').then((m) => m.readFile(pdfPath));
  const pdfDoc = await PDFDocument.load(pdfBytes);
  const actualPages = pdfDoc.getPageCount();
  if (actualPages !== expectedPages) {
    throw new Error(`Expected exactly ${expectedPages} pages, got ${actualPages} for ${pdfPath}`);
  }
}

async function openInFinder(paths) {
  for (const filePath of paths) {
    await execFileAsync('open', ['-R', filePath]);
  }
  if (paths.length > 0) {
    await execFileAsync('open', [resolve(paths[0], '..')]);
  }
}

async function run() {
  await app.whenReady();

  const outputDir = join(OUTPUT_ROOT, new Date().toISOString().replace(/[:.]/g, '-'));
  const tracePath = join(outputDir, 'trace.log');
  await rm(outputDir, { recursive: true, force: true });
  await mkdir(outputDir, { recursive: true });
  const log = async (msg) => {
    const line = `[${new Date().toISOString()}] ${msg}\n`;
    await appendFile(tracePath, line, 'utf8');
    console.log(msg);
  };

  const generatedPdfs = [];
  const printWindow = createPrintWindow();

  for (const testCase of CASES) {
    await log(`START ${testCase.name}`);
    const htmlPath = join(outputDir, `${testCase.name}.html`);
    const pdfPath = join(outputDir, `${testCase.name}.pdf`);

    await writeFile(htmlPath, testCase.html, 'utf8');
    await log(`WROTE_HTML ${htmlPath}`);
    await renderHtmlToPdf(printWindow, htmlPath, pdfPath, testCase.printOptions);
    await log(`WROTE_PDF ${pdfPath}`);
    await validatePdf(pdfPath, testCase.expectedPages);
    await log(`VALIDATED_PDF ${pdfPath}`);

    generatedPdfs.push(pdfPath);
    await log(`PASS ${testCase.name} -> ${pdfPath}`);
  }

  await log(`Generated ${generatedPdfs.length} PDFs in ${outputDir}`);

  if (shouldOpenFinder) {
    await openInFinder(generatedPdfs);
    await log('Opened generated PDFs in Finder.');
  }

  if (!printWindow.isDestroyed()) {
    printWindow.destroy();
  }
}

run()
  .then(() => {
    app.quit();
  })
  .catch((error) => {
    console.error('[pdf-integration-smoke] FAILED:', error);
    app.exit(1);
  });
